/** The page's class names, written as in the design ("btn pri lg"), mapped to this module's.
 * A name the module does not define (such as the theme's `dark`) passes through as is. */
export function c(names: string) {
  return names
    .split(' ')
    .map((n) => s[n] ?? n)
    .join(' ')
}

